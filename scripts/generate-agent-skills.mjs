#!/usr/bin/env node
/**
 * Keeps the agent skills' derived content in step with the sources it comes from.
 *
 *   cli/agent/skills/volt-ui-component-selection/SKILL.md   the generated catalog block
 *   src/server/routes/mcp/responsibilities.generated.ts      what the MCP `find_components` tool reads
 *   VOLT_UI_PROMPT.md                                        the catalog block (selectors read from the library)
 *   .agents/skills/volt-ui (and volt-ui-*)                    copies for agents working in this repo
 *
 * The skills themselves are hand-written and live only in cli/agent/skills. Component facts (status,
 * summary, where a component stops) come from `scripts/lib/component-catalog.mjs`.
 *
 *   node scripts/generate-agent-skills.mjs           write
 *   node scripts/generate-agent-skills.mjs --check   write nothing; exit 1 if stale
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { loadCatalog } from './lib/component-catalog.mjs';
import { librarySelectors } from './lib/selectors.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS = join(ROOT, 'cli/agent/skills');
const SELECTION = join(SKILLS, 'volt-ui-component-selection/SKILL.md');
const RESPONSIBILITIES = join(ROOT, 'src/server/routes/mcp/responsibilities.generated.ts');
const PROMPT = join(ROOT, 'VOLT_UI_PROMPT.md');
const REPO_SKILLS = join(ROOT, '.agents/skills');
const check = process.argv.includes('--check');
const stale = [];

const CATALOG = /<!-- volt:catalog:start -->[\s\S]*?<!-- volt:catalog:end -->/;

function catalogBlock(catalog) {
  const byCategory = new Map();
  for (const c of catalog) {
    byCategory.set(c.category, [...(byCategory.get(c.category) ?? []), c]);
  }
  const lines = ['<!-- volt:catalog:start -->'];
  for (const [category, items] of byCategory) {
    lines.push('', `### ${category}`, '');
    for (const c of items) {
      lines.push(`- **${c.title}** (\`${c.key}\`, ${c.status}) — ${c.summary}`);
      for (const n of c.notFor) lines.push(`  - Not for: ${n}`);
      if (c.related.length)
        lines.push(`  - See also: ${c.related.map(r => `\`${r}\``).join(', ')}`);
    }
  }
  lines.push('', '<!-- volt:catalog:end -->');
  return lines.join('\n');
}

async function prettify(path, text) {
  const config = (await resolveConfig(path)) ?? {};
  return format(text, { ...config, filepath: path });
}

function sync(path, content) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current === content) return;
  if (check) {
    stale.push(path.replace(ROOT + '/', ''));
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`[agent-skills] wrote ${path.replace(ROOT + '/', '')}`);
}

const catalog = await loadCatalog();

/** `^21.2.0 || ^22.0.0` → `21 and 22` (the major versions the peer range admits). */
function angularSupport() {
  const peer = JSON.parse(readFileSync(join(ROOT, 'projects/volt/package.json'), 'utf8'))
    .peerDependencies['@angular/core'];
  const majors = [...peer.matchAll(/(\d+)\.\d+\.\d+/g)].map(m => m[1]);
  return majors.length > 1 ? `${majors.slice(0, -1).join(', ')} and ${majors.at(-1)}` : majors[0];
}

// 1. the catalog inside the selection skill
const selection = readFileSync(SELECTION, 'utf8');
if (!CATALOG.test(selection))
  throw new Error('component-selection SKILL.md lost its catalog markers');
const selectionOut = await prettify(SELECTION, selection.replace(CATALOG, catalogBlock(catalog)));
sync(SELECTION, selectionOut);

// 2. the MCP responsibilities
const body = `/**
 * GENERATED by scripts/generate-agent-skills.mjs from the Storybook guides and COMPONENT_STATUS.md.
 * Do not edit. Run \`pnpm generate:agent-skills\` after changing a guide or a status.
 */

export interface ComponentResponsibility {
  title: string;
  category: string;
  status: 'stable' | 'beta' | 'experimental';
  summary: string;
  useWhen: string[];
  notFor: string[];
  related: string[];
}

/** The Angular versions the package supports: its peer dependency, so no prose has to repeat it. */
export const ANGULAR_SUPPORT = ${JSON.stringify(angularSupport())};

export const RESPONSIBILITIES: Record<string, ComponentResponsibility> = ${JSON.stringify(
  Object.fromEntries(catalog.map(({ key, ...rest }) => [key, rest])),
  null,
  2
)};
`;
sync(RESPONSIBILITIES, await prettify(RESPONSIBILITIES, body));

// 3. the catalog inside the single-file prompt: selectors come from the library source
const camel = name =>
  name
    .split('-')
    .map(p => p[0].toUpperCase() + p.slice(1))
    .join('');
/** `volt-card` → `<ui-card>`, `button[voltButton]` → `<button uiButton>`, `[voltDialog]` → `[uiDialog]`. */
function copyName(selector) {
  const m = selector.match(/^([a-z][a-z0-9-]*)?((?:\[[^\]]+\])*)$/);
  if (!m) return `\`${selector}\``;
  const [, tag = '', attrs = ''] = m;
  const renamedAttrs = attrs.replace(/\[volt/g, '[ui');
  if (tag.startsWith('volt-')) return `\`<${tag.replace(/^volt-/, 'ui-')}>\``;
  if (tag && renamedAttrs) return `\`<${tag} ${renamedAttrs.slice(1, -1).split('][').join(' ')}>\``;
  return `\`${renamedAttrs}\``;
}
function promptCatalog() {
  const selectors = librarySelectors();
  const rows = catalog
    .filter(c => selectors.has(c.key))
    .map(c => {
      const names = [...new Set(selectors.get(c.key).map(copyName))].sort();
      return `| ${c.title} | ${c.status} | \`./ui/${c.key}\` | ${names.join(', ')} |`;
    });
  return [
    '<!-- volt:catalog:start -->',
    '',
    '| Component | Status | Import (copy mode) | Selectors |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
    '<!-- volt:catalog:end -->',
  ].join('\n');
}
const prompt = readFileSync(PROMPT, 'utf8');
if (!CATALOG.test(prompt)) throw new Error('VOLT_UI_PROMPT.md lost its catalog markers');
sync(PROMPT, await prettify(PROMPT, prompt.replace(CATALOG, promptCatalog())));

// 4. copies for agents working in this repository (Codex/Kimi read .agents/skills)
const names = readdirSync(SKILLS, { withFileTypes: true })
  .filter(d => d.isDirectory())
  .map(d => d.name);
for (const name of names) {
  const source =
    name === 'volt-ui-component-selection'
      ? selectionOut
      : readFileSync(join(SKILLS, name, 'SKILL.md'), 'utf8');
  const target = join(REPO_SKILLS, name, 'SKILL.md');
  sync(target, await prettify(target, source));
}
// A skill removed from cli/agent/skills must not linger in .agents/skills.
for (const d of readdirSync(REPO_SKILLS, { withFileTypes: true })) {
  if (d.isDirectory() && d.name.startsWith('volt-ui') && !names.includes(d.name)) {
    if (check) stale.push(`.agents/skills/${d.name} (no longer a skill)`);
    else rmSync(join(REPO_SKILLS, d.name), { recursive: true });
  }
}

if (check) {
  if (stale.length) {
    console.error(
      `[agent-skills] stale:\n  - ${stale.join('\n  - ')}\nRun \`pnpm generate:agent-skills\` and commit the result.`
    );
    process.exit(1);
  }
  console.log('[agent-skills] up to date');
}
