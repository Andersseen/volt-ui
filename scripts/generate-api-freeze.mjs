#!/usr/bin/env node
/**
 * v0.9 Phase 3: generates the API-freeze reference — every public selector,
 * className, input, output, and CVA variant, extracted straight from source.
 * This becomes specs/api-freeze-0.9.md, which v1.0 Phase 1 diffs the final
 * API against (the only allowed differences at that point are removed
 * deprecated aliases).
 *
 * Parsing logic is shared with scripts/generate-api-reference.mjs via
 * scripts/lib/api-extract.mjs so the two outputs can never drift.
 *
 * Usage: node scripts/generate-api-freeze.mjs
 * Writes: specs/api-freeze-0.9.md
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { listComponentDirs, processComponentDir } from './lib/api-extract.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const COMP_ROOT = join(ROOT, 'projects/volt/src/lib/components');
const LAYOUT_ROOT = join(ROOT, 'projects/volt/src/lib/layouts');
const OUT_FILE = join(ROOT, 'specs/api-freeze-0.9.md');

// theme.ts exposes provideVoltTheme()/applyVoltTheme() functions, not a
// directive/component — nothing for this extractor to find.
const EXEMPT = new Set(['theme']);

// Markdown table cells split on unescaped `|` — TS union types (`string | null`)
// and some default-value expressions contain literal pipes, which would
// otherwise silently corrupt every table with a union-typed input/output.
function escapePipes(value) {
  return String(value).replace(/\|/g, '\\|');
}

function fmtDefault(input) {
  if (input.required) return '*(required)*';
  if (input.default === undefined) return '';
  return `\`${escapePipes(input.default)}\``;
}

function fmtType(value) {
  return `\`${escapePipes(value)}\``;
}

function renderComponentSection(name, directives, variants) {
  const lines = [`### \`${name}\``, ''];

  for (const d of directives) {
    lines.push(`**${d.className}** — selector: \`${escapePipes(d.selector ?? '(none found)')}\``, '');

    if (d.inputs.length > 0) {
      lines.push('| Input | Type | Default | Transform |', '| --- | --- | --- | --- |');
      for (const i of d.inputs) {
        lines.push(`| \`${i.name}\` | ${fmtType(i.type)} | ${fmtDefault(i)} | ${i.transform ?? ''} |`);
      }
      lines.push('');
    }

    if (d.outputs.length > 0) {
      lines.push('| Output | Type |', '| --- | --- |');
      for (const o of d.outputs) {
        lines.push(`| \`${o.name}\` | ${fmtType(o.type)} |`);
      }
      lines.push('');
    }
  }

  if (variants) {
    lines.push('**CVA variants:**', '');
    lines.push('| Group | Options | Default |', '| --- | --- | --- |');
    for (const [key, options] of Object.entries(variants.variants)) {
      const defaultValue = variants.defaults[key];
      lines.push(
        `| \`${key}\` | ${options.map(o => `\`${escapePipes(o)}\``).join(', ')} | ${
          defaultValue !== undefined ? `\`${escapePipes(defaultValue)}\`` : ''
        } |`
      );
    }
    lines.push('');
  }

  return lines.join('\n');
}

const componentNames = [
  ...listComponentDirs(COMP_ROOT).map(name => ({ name, root: COMP_ROOT })),
  ...listComponentDirs(LAYOUT_ROOT).map(name => ({ name, root: LAYOUT_ROOT })),
]
  .filter(({ name }) => !EXEMPT.has(name))
  .sort((a, b) => a.name.localeCompare(b.name));

const sections = [];
let totalDirectives = 0;
let totalInputs = 0;
let totalOutputs = 0;

for (const { name, root } of componentNames) {
  const { directives, variants } = processComponentDir(join(root, name));
  if (directives.length === 0) continue;
  totalDirectives += directives.length;
  for (const d of directives) {
    totalInputs += d.inputs.length;
    totalOutputs += d.outputs.length;
  }
  sections.push(renderComponentSection(name, directives, variants));
}

const header = `# API Freeze Reference — v0.9.0

Generated by \`node scripts/generate-api-freeze.mjs\` from the actual component
source (\`scripts/lib/api-extract.mjs\`, shared with
\`scripts/generate-api-reference.mjs\`) — not hand-maintained, so it can't drift
from what's actually shipped. Regenerate after any input/output/selector/CVA
change and re-check the diff into git.

This is the frozen reference for v1.0 Phase 1 ("Diff current public API
against \`specs/api-freeze-0.9.md\` — the only allowed differences are removed
deprecated aliases. Any other drift is a bug.").

**Snapshot:** ${componentNames.length} component directories, ${totalDirectives} exported directives/components, ${totalInputs} inputs, ${totalOutputs} outputs.

---

`;

writeFileSync(OUT_FILE, header + sections.join('\n---\n\n') + '\n');
console.log(
  `Wrote ${componentNames.length} components (${totalDirectives} directives, ${totalInputs} inputs, ${totalOutputs} outputs) to ${OUT_FILE}`
);
