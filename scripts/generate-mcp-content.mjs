#!/usr/bin/env node
/**
 * Writes src/server/routes/mcp/content.generated.ts from cli/mcp/content.js, the single source of
 * the files the @voltui/mcp installer writes. The hosted /api/mcp/setup endpoint serves this copy,
 * so the installer and the endpoint can no longer drift apart.
 *
 *   node scripts/generate-mcp-content.mjs           # write
 *   node scripts/generate-mcp-content.mjs --check   # write nothing; exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = join(ROOT, 'src/server/routes/mcp/content.generated.ts');
const { DEFAULT_MCP_URL, buildContent } = createRequire(import.meta.url)(
  join(ROOT, 'cli/mcp/content.js')
);

const content = buildContent(DEFAULT_MCP_URL);
const header = `/**
 * GENERATED by scripts/generate-mcp-content.mjs from cli/mcp/content.js. Do not edit.
 * Run \`pnpm generate:mcp-content\` after changing the installer content.
 */

export const MCP_URL = ${JSON.stringify(DEFAULT_MCP_URL)};

`;
const body = Object.entries(content)
  .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};`)
  .join('\n\n');

const config = (await resolveConfig(OUT_FILE)) ?? {};
const output = await format(header + body + '\n', { ...config, filepath: OUT_FILE });

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT_FILE, 'utf8');
  } catch {
    // missing counts as stale
  }
  if (current !== output) {
    console.error(
      `[mcp-content] ${OUT_FILE} is stale.\nRun \`pnpm generate:mcp-content\` and commit the result.`
    );
    process.exit(1);
  }
  console.log('[mcp-content] up to date');
} else {
  writeFileSync(OUT_FILE, output);
  console.log(`[mcp-content] wrote ${OUT_FILE}`);
}
