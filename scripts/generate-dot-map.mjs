#!/usr/bin/env node
/**
 * Builds the dotted map for the Recipes "Contact Map" block.
 *
 *   node scripts/generate-dot-map.mjs [--country 756] [--pin 7.45,46.95] \
 *     [--bounds -24,44,57,34] [--step 0.56] [--out <file>]
 *
 * Samples a square grid against Natural Earth country shapes (world-atlas, 1:50m) and writes a
 * TypeScript data file with two SVG paths of zero-length segments, one `M x y h0` per dot drawn
 * with round caps: one path for the highlighted country and one for every other country. About
 * 1,700 dots come to roughly 6 KB gzipped, and render on the server with no request.
 *
 * - `--country`: ISO 3166-1 numeric code, as world-atlas uses for feature ids (756 Switzerland,
 *   724 Spain, 380 Italy, 250 France…).
 * - `--pin`: longitude,latitude of the pulsing pin.
 * - `--bounds`: west,east,north,south in degrees. Anything outside is skipped, which is also how
 *   far-away overseas territories drop out.
 * - `--step`: distance between dots in latitude degrees.
 *
 * Longitude degrees shrink with latitude, so the grid is sampled in a projection scaled by the
 * cosine of the middle latitude: the dots stay square instead of stretching east to west.
 *
 * No dependency: the topology is fetched once from a pinned world-atlas release on jsDelivr and
 * decoded here (TopoJSON arcs are delta-encoded integers; see decodeArc), so neither
 * `world-atlas` nor `topojson-client` has to be installed. The generated file is committed and
 * the block never runs this.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json';

const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? args[index + 1] : fallback;
};
const numbers = value => value.split(',').map(Number);

const COUNTRY = arg('country', '756');
const [PIN_LON, PIN_LAT] = numbers(arg('pin', '7.45,46.95'));
const [WEST, EAST, NORTH, SOUTH] = numbers(arg('bounds', '-24,44,57,34'));
const STEP = Number(arg('step', '0.56'));
const OUT = arg('out', join(ROOT, 'apps/recipes/src/app/blocks/contact-map/contact-map.data.ts'));
/** Pixels per degree of latitude in the output viewBox. */
const UNIT = 10;
const LON_SCALE = Math.cos((((NORTH + SOUTH) / 2) * Math.PI) / 180);

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: ${response.status}`);
const topology = await response.json();

/** A TopoJSON arc: quantized deltas, summed, then mapped back to degrees. */
const { scale, translate } = topology.transform;
const arcs = topology.arcs.map(arc => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
/** A negative index (~i) means arc i walked backwards. */
const decodeArc = index => (index < 0 ? [...arcs[~index]].reverse() : arcs[index]);
const ring = indexes => indexes.flatMap((index, i) => decodeArc(index).slice(i ? 1 : 0));

const countries = topology.objects.countries.geometries
  .filter(geometry => geometry.type === 'Polygon' || geometry.type === 'MultiPolygon')
  .map(geometry => ({
    id: String(geometry.id),
    polygons: (geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs).map(polygon =>
      polygon.map(ring)
    ),
  }));

function inRing(lon, lat, points) {
  let hit = false;
  for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
    const [xi, yi] = points[i];
    const [xj, yj] = points[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

const inCountry = (lon, lat, country) =>
  country.polygons.some(
    ([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some(hole => inRing(lon, lat, hole))
  );

const round = value => Math.round(value * 10) / 10;
const project = (lon, lat) => [
  round((lon - WEST) * LON_SCALE * UNIT),
  round((NORTH - lat) * UNIT),
];

const highlight = [];
const rest = [];
for (let lat = NORTH; lat >= SOUTH; lat -= STEP) {
  for (let lon = WEST; lon <= EAST; lon += STEP / LON_SCALE) {
    const owner = countries.find(country => inCountry(lon, lat, country));
    if (!owner) continue;
    (owner.id === COUNTRY ? highlight : rest).push(project(lon, lat));
  }
}

if (highlight.length === 0) {
  throw new Error(`No dot landed in country ${COUNTRY}: check the id, the bounds or the step.`);
}

const path = points => points.map(([x, y]) => `M${x} ${y}h0`).join('');
const [width, height] = project(EAST, SOUTH);
const [pinX, pinY] = project(PIN_LON, PIN_LAT);

writeFileSync(
  OUT,
  `// Generated by scripts/generate-dot-map.mjs from Natural Earth (world-atlas 2.0.2). Do not edit.\n` +
    `// node scripts/generate-dot-map.mjs --country ${COUNTRY} --pin ${PIN_LON},${PIN_LAT} ` +
    `--bounds ${WEST},${EAST},${NORTH},${SOUTH} --step ${STEP}\n` +
    `export const CONTACT_MAP = {\n` +
    `  width: ${width},\n  height: ${height},\n  pin: { x: ${pinX}, y: ${pinY} },\n` +
    `  highlight: '${path(highlight)}',\n  rest: '${path(rest)}',\n} as const;\n`
);
console.log(
  `Dot map: ${rest.length + highlight.length} dots (${highlight.length} in ${COUNTRY}), ${width}×${height} → ${OUT}`
);
