// Consumer-safety regressions for `volt init` and `volt add`, driven through the real binary in
// throwaway project roots. None of these scenarios relies on --force unless --force is the subject.
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { spawnSync } from 'node:child_process';
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import * as fs from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative, resolve } from 'node:path';

const core = require('../lib/core.js');
const { planAdd, PlanError } = require('../lib/add-plan.js');
const { applyPlan, ApplyError } = require('../lib/apply-plan.js');
const { INITIAL_BARREL } = require('../lib/barrel.js');

const CLI = resolve(__dirname, '../bin/volt');
const manifest = core.getLocalManifest();
const isRoot = typeof process.getuid === 'function' && process.getuid() === 0;

function volt(cwd, ...args) {
  const result = spawnSync('node', [CLI, ...args], { cwd, encoding: 'utf-8' });
  return { status: result.status, out: `${result.stdout}${result.stderr}` };
}

/** Every directory and file under `root`, with exact bytes, for before/after comparisons. */
function snapshot(root) {
  const entries = {};
  if (!existsSync(root)) return entries;
  const walk = dir => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      const key = relative(root, full);
      if (entry.isDirectory()) {
        entries[`${key}/`] = 'dir';
        walk(full);
      } else {
        entries[key] = readFileSync(full).toString('base64');
      }
    }
  };
  walk(root);
  return entries;
}

const read = file => readFileSync(file, 'utf-8');
const count = (haystack, needle) => haystack.split(needle).length - 1;

const CUSTOM_BARREL = [
  '/**',
  ' * Our UI barrel — curated by hand. Do not regenerate.',
  ' */',
  "import './polyfills';",
  '',
  "export * from './my-widget';",
  "export { UiFancyCard as Card } from './fancy-card';",
  '// export * from "./legacy";',
  '',
  '',
  'export const UI_VERSION = 3   ;',
].join('\r\n'); // CRLF, no trailing newline, odd spacing: all of it must survive

describe('CLI integrity', () => {
  let project;
  let ui;

  beforeEach(() => {
    project = mkdtempSync(join(tmpdir(), 'volt-integrity-'));
    writeFileSync(
      join(project, 'package.json'),
      JSON.stringify({ name: 'consumer', dependencies: { '@angular/core': '^22.0.0' } })
    );
    ui = join(project, 'src/app/ui');
  });

  afterEach(() => {
    // A read-only directory left by a failed assertion must not break the cleanup.
    try {
      chmodSync(join(ui, 'sidebar'), 0o755);
    } catch {
      /* not created by this test */
    }
    rmSync(project, { recursive: true, force: true });
  });

  describe('init', () => {
    it('creates the directory and the initial barrel in a new project', () => {
      const result = volt(project, 'init', ui);
      expect(result.status).toBe(0);
      expect(read(join(ui, 'index.ts'))).toBe(INITIAL_BARREL);
      expect(result.out).toContain('Created');
    });

    it('is idempotent: a second init changes nothing', () => {
      volt(project, 'init', ui);
      const before = snapshot(project);
      const result = volt(project, 'init', ui);
      expect(result.status).toBe(0);
      expect(result.out).toContain('Kept the existing');
      expect(snapshot(project)).toEqual(before);
    });

    it('preserves a custom barrel byte for byte (comments, imports, exports, CRLF, formatting)', () => {
      mkdirSync(ui, { recursive: true });
      writeFileSync(join(ui, 'index.ts'), CUSTOM_BARREL);
      writeFileSync(join(ui, 'my-widget.ts'), 'export const widget = 1;\n');
      const before = snapshot(project);

      expect(volt(project, 'init', ui).status).toBe(0);
      expect(volt(project, 'init', ui).status).toBe(0);
      expect(snapshot(project)).toEqual(before);
    });

    it('preserves an empty index.ts', () => {
      mkdirSync(ui, { recursive: true });
      writeFileSync(join(ui, 'index.ts'), '');
      expect(volt(project, 'init', ui).status).toBe(0);
      expect(read(join(ui, 'index.ts'))).toBe('');
    });

    it('preserves a barrel generated by earlier add operations', () => {
      volt(project, 'init', ui);
      volt(project, 'add', 'button', 'badge', ui);
      const before = snapshot(project);
      expect(read(join(ui, 'index.ts'))).toContain("export * from './badge';");

      expect(volt(project, 'init', ui).status).toBe(0);
      expect(snapshot(project)).toEqual(before);
    });

    it('initProject keeps every kind of existing barrel and reports it', () => {
      const barrels = {
        empty: '',
        generated: `${INITIAL_BARREL}export * from './button';\n`,
        custom: CUSTOM_BARREL,
        several: "export * from './a';\nexport * from './b';\nexport * from './c';\n",
        unusual: 'export*from\'./a\'\n\n\n   export   {   b   }   from   "./b"   ;',
      };
      for (const [name, content] of Object.entries(barrels)) {
        const dir = join(project, name);
        mkdirSync(dir);
        writeFileSync(join(dir, 'index.ts'), content);
        const result = core.initProject(dir);
        expect(result.createdIndex).toBe(false);
        expect(readFileSync(join(dir, 'index.ts'))).toEqual(Buffer.from(content));
      }
    });

    it('refuses a target that is a file, without touching it', () => {
      writeFileSync(join(project, 'ui'), 'not a directory');
      const result = volt(project, 'init', './ui');
      expect(result.status).toBe(1);
      expect(result.out).toContain('is not a directory');
      expect(read(join(project, 'ui'))).toBe('not a directory');
    });

    it.skipIf(isRoot)('explains a permission error instead of printing a stack trace', () => {
      const locked = join(project, 'locked');
      mkdirSync(locked);
      chmodSync(locked, 0o555);
      try {
        const result = volt(project, 'init', join(locked, 'ui'));
        expect(result.status).toBe(1);
        expect(result.out).toContain('permission denied');
        expect(result.out).not.toContain('    at ');
      } finally {
        chmodSync(locked, 0o755);
      }
    });
  });

  describe('single add', () => {
    it('adds button with its shared helper and barrel export', () => {
      const result = volt(project, 'add', 'button', ui);
      expect(result.status).toBe(0);
      expect(read(join(ui, 'button/button.ts'))).toContain('class UiButton');
      expect(existsSync(join(ui, 'utils.ts'))).toBe(true);
      expect(read(join(ui, 'index.ts'))).toContain("export * from './button';");
    });

    it('re-adding an untouched component reuses every file and changes nothing', () => {
      volt(project, 'add', 'button', ui);
      const before = snapshot(project);
      const result = volt(project, 'add', 'button', ui);
      expect(result.status).toBe(0);
      expect(result.out).toContain('0 created');
      expect(result.out).toMatch(/\d+ reused/);
      expect(snapshot(project)).toEqual(before);
    });

    it('refuses to overwrite an edited component, naming the file and the way out', () => {
      volt(project, 'add', 'button', ui);
      writeFileSync(join(ui, 'button/button.ts'), '// my button\n');
      const before = snapshot(project);

      const result = volt(project, 'add', 'button', ui);
      expect(result.status).toBe(1);
      expect(result.out).toContain(join(ui, 'button/button.ts'));
      expect(result.out).toContain('component button');
      expect(result.out).toContain('--force');
      expect(result.out).toContain('different target-dir');
      expect(snapshot(project)).toEqual(before);
    });

    it('--force replaces the edited component and nothing unrelated', () => {
      volt(project, 'add', 'button', ui);
      writeFileSync(join(ui, 'button/button.ts'), '// my button\n');
      writeFileSync(join(ui, 'button/my-extra.ts'), '// mine\n');

      const result = volt(project, 'add', 'button', ui, '--force');
      expect(result.status).toBe(0);
      expect(result.out).toContain('1 replaced');
      expect(read(join(ui, 'button/button.ts'))).toContain('class UiButton');
      expect(read(join(ui, 'button/my-extra.ts'))).toBe('// mine\n');
    });

    it('a repeated name is one component', () => {
      expect(volt(project, 'add', 'button', 'button', ui).status).toBe(0);
      expect(count(read(join(ui, 'index.ts')), "export * from './button';")).toBe(1);
    });
  });

  describe('multi-add with shared dependencies', () => {
    it('adds tooltip + sidebar and sidebar + tooltip without --force, to the same files', () => {
      const other = join(project, 'other');
      const first = volt(project, 'add', 'tooltip', 'sidebar', ui);
      const second = volt(project, 'add', 'sidebar', 'tooltip', other);
      expect(first.status).toBe(0);
      expect(second.status).toBe(0);

      const files = tree =>
        Object.fromEntries(Object.entries(snapshot(tree)).filter(([k]) => k !== 'index.ts'));
      expect(files(other)).toEqual(files(ui));
      for (const name of ['tooltip', 'sidebar', 'theme']) {
        expect(existsSync(join(ui, name, 'index.ts'))).toBe(true);
      }
    });

    it('plans each shared dependency and helper exactly once', () => {
      const plan = planAdd({ componentNames: ['sidebar', 'tooltip'], targetDir: ui, manifest });
      const paths = plan.files.map(f => f.targetPath);
      expect(new Set(paths).size).toBe(paths.length);
      expect(plan.requested).toEqual(['sidebar', 'tooltip']);
      expect(plan.dependencies).toEqual(['theme']);
      expect(paths.filter(p => p.endsWith('utils.ts'))).toHaveLength(1);
      expect(plan.files.every(f => f.action === 'create')).toBe(true);
    });

    it('exports every component once', () => {
      volt(project, 'add', 'tooltip', 'sidebar', ui);
      volt(project, 'add', 'sidebar', 'tooltip', ui);
      const barrel = read(join(ui, 'index.ts'));
      for (const name of ['tooltip', 'sidebar', 'theme']) {
        expect(count(barrel, `export * from './${name}';`)).toBe(1);
      }
    });

    it('a second operation keeps the files of the first', () => {
      expect(volt(project, 'add', 'tooltip', ui).status).toBe(0);
      const tooltip = snapshot(join(ui, 'tooltip'));
      const result = volt(project, 'add', 'sidebar', ui);
      expect(result.status).toBe(0);
      expect(snapshot(join(ui, 'tooltip'))).toEqual(tooltip);
      expect(existsSync(join(ui, 'sidebar/sidebar.ts'))).toBe(true);
    });

    it('appends to a custom barrel without rewriting or duplicating anything in it', () => {
      mkdirSync(ui, { recursive: true });
      const custom = [
        '// Hand-written barrel',
        "// export * from './button';", // commented out: still needs a real export
        'export * from "./badge";', // double quotes: already exported
        'export const x = 1;',
      ].join('\n');
      writeFileSync(join(ui, 'index.ts'), custom);

      expect(volt(project, 'add', 'button', 'badge', ui).status).toBe(0);
      const barrel = read(join(ui, 'index.ts'));
      expect(barrel.startsWith(`${custom}\n`)).toBe(true);
      expect(barrel.slice(custom.length + 1)).toBe("export * from './button';\n");
    });

    it('reports the unique components and the shared dependencies', () => {
      const result = volt(project, 'add', 'tooltip', 'sidebar', 'tooltip', ui);
      expect(result.status).toBe(0);
      expect(result.out).toContain('Added 2 component(s)');
      expect(count(result.out, '  - tooltip')).toBe(1);
      expect(result.out).toContain('  - sidebar');
      expect(result.out).toMatch(/Required dependencies:\n {2}- theme/);
      expect(result.out).toContain('Shared helpers: utils.ts');
    });
  });

  describe('shared helpers', () => {
    it('reuses an identical shared helper', () => {
      volt(project, 'add', 'button', ui);
      const utils = readFileSync(join(ui, 'utils.ts'));
      const plan = planAdd({ componentNames: ['badge'], targetDir: ui, manifest });
      expect(plan.files.find(f => f.targetPath.endsWith('utils.ts')).action).toBe('reuse');

      expect(volt(project, 'add', 'badge', ui).status).toBe(0);
      expect(readFileSync(join(ui, 'utils.ts'))).toEqual(utils);
    });

    it('rejects a modified shared helper and writes nothing', () => {
      volt(project, 'add', 'button', ui);
      writeFileSync(join(ui, 'utils.ts'), '// my utils\n');
      const before = snapshot(project);

      const result = volt(project, 'add', 'badge', ui);
      expect(result.status).toBe(1);
      expect(result.out).toContain(`${join(ui, 'utils.ts')} (shared helper)`);
      expect(result.out).toContain('--force');
      expect(snapshot(project)).toEqual(before);
      expect(existsSync(join(ui, 'badge'))).toBe(false);
    });

    it('replaces a modified shared helper with an explicit --force', () => {
      volt(project, 'add', 'button', ui);
      writeFileSync(join(ui, 'utils.ts'), '// my utils\n');
      expect(volt(project, 'add', 'badge', ui, '--force').status).toBe(0);
      expect(read(join(ui, 'utils.ts'))).toContain('export function cn');
    });

    it('treats a line-ending-only difference as identical', () => {
      volt(project, 'add', 'button', ui);
      writeFileSync(join(ui, 'utils.ts'), read(join(ui, 'utils.ts')).replace(/\n/g, '\r\n'));
      const crlf = readFileSync(join(ui, 'utils.ts'));
      expect(volt(project, 'add', 'badge', ui).status).toBe(0);
      expect(readFileSync(join(ui, 'utils.ts'))).toEqual(crlf);
    });
  });

  describe('failure safety', () => {
    it('a conflict in a later component means zero filesystem changes', () => {
      mkdirSync(join(ui, 'card'), { recursive: true });
      writeFileSync(join(ui, 'card/card.ts'), '// my card\n');
      writeFileSync(join(ui, 'index.ts'), CUSTOM_BARREL);
      const before = snapshot(project);

      const result = volt(project, 'add', 'button', 'badge', 'card', ui);
      expect(result.status).toBe(1);
      expect(result.out).toContain(join(ui, 'card/card.ts'));
      expect(snapshot(project)).toEqual(before);
    });

    it('an unsupported component in a mixed request writes nothing', () => {
      volt(project, 'add', 'button', ui);
      const before = snapshot(project);
      const result = volt(
        project,
        'add',
        'checkbox',
        'button',
        join(project, 'q'),
        '--base=quartz'
      );
      expect(result.status).toBe(1);
      expect(snapshot(project)).toEqual(before);
    });

    it('an unknown component or a missing source fails planning before any write', () => {
      expect(() =>
        planAdd({ componentNames: ['button', 'nope'], targetDir: ui, manifest })
      ).toThrow(PlanError);

      const broken = {
        ...manifest,
        components: {
          ...manifest.components,
          ghost: { files: ['components/ghost/ghost.ts'], dependencies: [] },
        },
      };
      let error;
      try {
        planAdd({ componentNames: ['button', 'ghost'], targetDir: ui, manifest: broken });
      } catch (err) {
        error = err;
      }
      expect(error).toBeInstanceOf(PlanError);
      expect(error.code).toBe('MISSING_SOURCE');
      expect(error.message).toContain('components/ghost/ghost.ts');
      expect(existsSync(ui)).toBe(false);
    });

    it('a failing write restores replaced files and removes only what the operation created', () => {
      // Existing consumer state: an edited button (to be replaced with --force), a custom barrel,
      // an unrelated file, and a pre-existing component directory.
      volt(project, 'add', 'button', ui);
      writeFileSync(join(ui, 'button/button.ts'), '// my button\n');
      writeFileSync(join(ui, 'index.ts'), CUSTOM_BARREL);
      writeFileSync(join(ui, 'mine.ts'), '// unrelated\n');
      const before = snapshot(project);

      const plan = planAdd({
        componentNames: ['button', 'tooltip', 'sidebar'],
        targetDir: ui,
        manifest,
        force: true,
      });
      expect(plan.files.some(f => f.action === 'replace')).toBe(true);
      const writes = plan.files.filter(f => f.action !== 'reuse').length;
      expect(writes).toBeGreaterThan(4);

      let calls = 0;
      const failing = {
        ...fs,
        writeFileSync(target, ...rest) {
          calls += 1;
          if (calls === writes - 1)
            throw Object.assign(new Error('EIO: disk failed'), { code: 'EIO' });
          return fs.writeFileSync(target, ...rest);
        },
      };
      let error;
      try {
        applyPlan(plan, failing);
      } catch (err) {
        error = err;
      }
      expect(error).toBeInstanceOf(ApplyError);
      expect(error.message).toContain('EIO: disk failed');
      expect(error.message).toContain('rolled back');
      expect(error.restoreFailures).toEqual([]);
      expect(snapshot(project)).toEqual(before);
    });

    it('a failure writing the barrel rolls back every component file', () => {
      writeFileSync(join(project, 'keep.ts'), '// keep\n');
      const before = snapshot(project);
      const plan = planAdd({ componentNames: ['tooltip', 'sidebar'], targetDir: ui, manifest });
      const failing = {
        ...fs,
        openSync(target, ...rest) {
          if (resolve(String(target)) === resolve(plan.barrel.path)) {
            throw Object.assign(new Error('ENOSPC: no space left'), { code: 'ENOSPC' });
          }
          return fs.openSync(target, ...rest);
        },
      };
      expect(() => applyPlan(plan, failing)).toThrow(/ENOSPC/);
      expect(snapshot(project)).toEqual(before);
      expect(existsSync(join(project, 'src'))).toBe(false);
    });

    it.skipIf(isRoot)(
      'the real binary rolls back after a write failure and keeps pre-existing directories',
      () => {
        mkdirSync(join(ui, 'sidebar'), { recursive: true });
        writeFileSync(join(ui, 'index.ts'), CUSTOM_BARREL);
        writeFileSync(join(ui, 'mine.ts'), '// unrelated\n');
        chmodSync(join(ui, 'sidebar'), 0o555); // tooltip is written first, then sidebar fails
        const before = snapshot(project);

        const result = volt(project, 'add', 'tooltip', 'sidebar', ui);
        chmodSync(join(ui, 'sidebar'), 0o755);
        expect(result.status).toBe(1);
        expect(result.out).toContain('rolled back');
        expect(snapshot(project)).toEqual(before);
        expect(existsSync(join(ui, 'tooltip'))).toBe(false);
        expect(existsSync(join(ui, 'sidebar'))).toBe(true);
      }
    );
  });

  describe('dry run', () => {
    it('reports the real plan and has no side effects', () => {
      const result = volt(
        project,
        'add',
        'tooltip',
        'sidebar',
        ui,
        '--dry-run',
        '--install',
        '--base=ng-primitives'
      );
      expect(result.status).toBe(0);
      expect(result.out).toContain('Dry run');
      expect(result.out).toContain('Requested: tooltip, sidebar');
      expect(result.out).toContain('Dependencies: theme');
      expect(result.out).toContain('Shared files: utils.ts');
      expect(result.out).toContain("export * from './sidebar';");
      expect(result.out).toContain('Runtime dependencies would be installed');
      expect(readdirSync(project)).toEqual(['package.json']);
    });

    it('agrees with the real operation on what it creates and reuses', () => {
      volt(project, 'add', 'tooltip', ui);
      const dry = volt(project, 'add', 'tooltip', 'sidebar', ui, '--dry-run');
      const listed = action =>
        dry.out
          .split('\n')
          .filter(line => line.trimStart().startsWith(`${action} `))
          .map(line => line.trim().split(/\s+/)[1])
          .sort();

      const before = new Set(Object.keys(snapshot(ui)));
      expect(volt(project, 'add', 'tooltip', 'sidebar', ui).status).toBe(0);
      const created = Object.keys(snapshot(ui))
        .filter(key => !key.endsWith('/') && !before.has(key))
        .map(key => join(ui, key))
        .sort();
      expect(listed('create')).toEqual(created);
      expect(listed('reuse').length).toBeGreaterThan(0);
      expect(listed('reuse').every(file => before.has(relative(ui, file)))).toBe(true);
    });

    it('reports an existing conflict, exits non-zero and has no side effects', () => {
      volt(project, 'add', 'button', ui);
      writeFileSync(join(ui, 'utils.ts'), '// mine\n');
      const before = snapshot(project);

      const result = volt(project, 'add', 'badge', ui, '--dry-run');
      expect(result.status).toBe(1);
      expect(result.out).toContain(`conflict ${join(ui, 'utils.ts')}`);
      expect(result.out).toContain('would refuse');
      expect(snapshot(project)).toEqual(before);
    });

    it('with --force reports the replacement without making it', () => {
      volt(project, 'add', 'button', ui);
      writeFileSync(join(ui, 'utils.ts'), '// mine\n');
      const before = snapshot(project);
      const result = volt(project, 'add', 'badge', ui, '--dry-run', '--force');
      expect(result.status).toBe(0);
      expect(result.out).toContain(`replace  ${join(ui, 'utils.ts')}`);
      expect(snapshot(project)).toEqual(before);
    });
  });
});
